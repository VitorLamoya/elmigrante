export function getLanguageConfig(language) {
  return languages.find((item) => item.code === language) || languages[0];
}

export function createTranslator(language) {
  const dictionary = translations[language] || translations.pt;

  return function translate(path, fallback = path) {
    const value = path.split(".").reduce((current, key) => current?.[key], dictionary);
    return value ?? fallback;
  };
}
